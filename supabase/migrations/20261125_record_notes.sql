-- Private remarks for a Mumin or a Family.
-- This database's auth foundation exposes current_app_role(); these helpers
-- preserve the existing admin/editor role semantics used by table RLS.
create or replace function public.can_edit()
returns boolean
language sql
stable
as $$
  select public.current_app_role() in ('admin', 'editor');
$$;

create or replace function public.is_admin()
returns boolean
language sql
stable
as $$
  select public.current_app_role() = 'admin';
$$;

revoke all on function public.can_edit() from public;
revoke all on function public.is_admin() from public;
grant execute on function public.can_edit() to authenticated;
grant execute on function public.is_admin() to authenticated;

create table if not exists public.record_notes (
  id bigint generated by default as identity primary key,
  mumin_id bigint references public.mumin_data(id) on delete cascade,
  -- No FK on family_id because the historical migrations have varied types.
  family_id bigint,
  note text not null check (length(trim(note)) between 1 and 5000),
  is_printable boolean not null default false,
  created_by text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint record_notes_one_target check ((mumin_id is null) <> (family_id is null))
);

create index if not exists record_notes_mumin_idx on public.record_notes (mumin_id) where mumin_id is not null;
create index if not exists record_notes_family_idx on public.record_notes (family_id) where family_id is not null;

alter table public.record_notes enable row level security;

drop policy if exists record_notes_select_editors on public.record_notes;
create policy record_notes_select_editors on public.record_notes
  for select to authenticated using ((select public.can_edit()));

drop policy if exists record_notes_insert_editors on public.record_notes;
create policy record_notes_insert_editors on public.record_notes
  for insert to authenticated with check ((select public.can_edit()));

drop policy if exists record_notes_update_editors on public.record_notes;
create policy record_notes_update_editors on public.record_notes
  for update to authenticated
  using ((select public.can_edit())) with check ((select public.can_edit()));

drop policy if exists record_notes_delete_admins on public.record_notes;
create policy record_notes_delete_admins on public.record_notes
  for delete to authenticated using ((select public.is_admin()));

grant select, insert, update, delete on public.record_notes to authenticated;
grant usage, select on sequence public.record_notes_id_seq to authenticated;
