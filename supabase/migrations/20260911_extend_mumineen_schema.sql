-- =====================================================================
-- Migration: extend Mumineen database schema
--
-- Purpose:
--   Extend the existing Husaini Mohallah schema for the 77-column Jamaat
--   export without replacing the existing mumin_data / sectors /
--   sub_sectors tables.
--
-- Source export:
--   1,584 individuals / 646 families.
--
-- Important:
--   This migration intentionally does NOT import the Excel data and does
--   NOT modify existing rows. Relationship values of 0 are normalized to
--   NULL by the import process, not by this schema migration.
--
-- Existing live schema verified before creating this migration:
--   mumin_data.its_number      text
--   mumin_data.name            text
--   mumin_data.sub_sector_id   bigint
--   mumin_data.area_sector     text
--   mumin_data.sabil_no        text
--   sectors.id                 bigint identity PK
--   sub_sectors.id             bigint identity PK
-- =====================================================================

BEGIN;

-- ---------------------------------------------------------------------
-- 1. FAMILIES
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.families (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    family_id TEXT NOT NULL UNIQUE,
    hof_its_number TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

COMMENT ON TABLE public.families IS
'Normalized family records derived from Jamaat Family_ID.';

CREATE INDEX IF NOT EXISTS idx_families_hof_its_number
    ON public.families (hof_its_number);

-- ---------------------------------------------------------------------
-- 2. EXTEND MUMIN_DATA
--    Existing application columns are preserved.
-- ---------------------------------------------------------------------
ALTER TABLE public.mumin_data
    ADD COLUMN IF NOT EXISTS family_id TEXT,
    ADD COLUMN IF NOT EXISTS hof_its_number TEXT,
    ADD COLUMN IF NOT EXISTS father_its_number TEXT,
    ADD COLUMN IF NOT EXISTS mother_its_number TEXT,
    ADD COLUMN IF NOT EXISTS spouse_its_number TEXT,
    ADD COLUMN IF NOT EXISTS hijri_age INTEGER,
    ADD COLUMN IF NOT EXISTS marital_status TEXT,
    ADD COLUMN IF NOT EXISTS blood_group TEXT,
    ADD COLUMN IF NOT EXISTS misaq TEXT,
    ADD COLUMN IF NOT EXISTS full_name_arabic TEXT,
    ADD COLUMN IF NOT EXISTS tanzeem_file_no TEXT,
    ADD COLUMN IF NOT EXISTS title TEXT,
    ADD COLUMN IF NOT EXISTS first_prefix TEXT,
    ADD COLUMN IF NOT EXISTS prefix_year TEXT,
    ADD COLUMN IF NOT EXISTS first_name TEXT,
    ADD COLUMN IF NOT EXISTS father_prefix TEXT,
    ADD COLUMN IF NOT EXISTS father_name TEXT,
    ADD COLUMN IF NOT EXISTS father_surname TEXT,
    ADD COLUMN IF NOT EXISTS husband_prefix TEXT,
    ADD COLUMN IF NOT EXISTS husband_name TEXT,
    ADD COLUMN IF NOT EXISTS surname TEXT,
    ADD COLUMN IF NOT EXISTS warakatul_tarkhis TEXT,
    ADD COLUMN IF NOT EXISTS date_of_nikah TEXT,
    ADD COLUMN IF NOT EXISTS date_of_nikah_hijri TEXT,
    ADD COLUMN IF NOT EXISTS quran_sanad TEXT,
    ADD COLUMN IF NOT EXISTS qadambosi_sharaf TEXT,
    ADD COLUMN IF NOT EXISTS raudat_tahera_ziyarat TEXT,
    ADD COLUMN IF NOT EXISTS karbala_ziyarat TEXT,
    ADD COLUMN IF NOT EXISTS ashara_mubaraka TEXT,
    ADD COLUMN IF NOT EXISTS last_scanned_event TEXT,
    ADD COLUMN IF NOT EXISTS last_scanned_place TEXT,
    ADD COLUMN IF NOT EXISTS whatsapp_no TEXT,
    ADD COLUMN IF NOT EXISTS qualification TEXT,
    ADD COLUMN IF NOT EXISTS languages TEXT,
    ADD COLUMN IF NOT EXISTS hunars TEXT,
    ADD COLUMN IF NOT EXISTS occupation TEXT,
    ADD COLUMN IF NOT EXISTS sub_occupation TEXT,
    ADD COLUMN IF NOT EXISTS sub_occupation2 TEXT,
    ADD COLUMN IF NOT EXISTS housing TEXT,
    ADD COLUMN IF NOT EXISTS type_of_house TEXT,
    ADD COLUMN IF NOT EXISTS building TEXT,
    ADD COLUMN IF NOT EXISTS street TEXT,
    ADD COLUMN IF NOT EXISTS area TEXT,
    ADD COLUMN IF NOT EXISTS state TEXT,
    ADD COLUMN IF NOT EXISTS city TEXT,
    ADD COLUMN IF NOT EXISTS pincode TEXT,
    ADD COLUMN IF NOT EXISTS vatan TEXT,
    ADD COLUMN IF NOT EXISTS nationality TEXT,
    ADD COLUMN IF NOT EXISTS jamaat TEXT,
    ADD COLUMN IF NOT EXISTS jamiaat TEXT,
    ADD COLUMN IF NOT EXISTS data_verification_status TEXT,
    ADD COLUMN IF NOT EXISTS data_verification_date TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS photo_verification_status TEXT,
    ADD COLUMN IF NOT EXISTS photo_verification_date TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS sector_incharge_its_number TEXT,
    ADD COLUMN IF NOT EXISTS sub_sector_incharge_its_number TEXT,
    ADD COLUMN IF NOT EXISTS sector_incharge_female_its_number TEXT,
    ADD COLUMN IF NOT EXISTS sub_sector_incharge_female_its_number TEXT;

-- ---------------------------------------------------------------------
-- 3. EXISTING SECTORS / SUB_SECTORS
--    These tables already exist in the live database, so do not recreate
--    or replace their primary-key model. Add only the normalized incharge
--    reference fields needed by the new export.
-- ---------------------------------------------------------------------
ALTER TABLE public.sectors
    ADD COLUMN IF NOT EXISTS incharge_its_number TEXT;

ALTER TABLE public.sub_sectors
    ADD COLUMN IF NOT EXISTS incharge_its_number TEXT;

-- ---------------------------------------------------------------------
-- 4. ORGANISATIONS + MANY-TO-MANY MEMBERSHIP
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.organisations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT NOT NULL UNIQUE,
    idara TEXT,
    category TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE TABLE IF NOT EXISTS public.mumineen_organisations (
    mumin_id BIGINT NOT NULL REFERENCES public.mumin_data(id) ON DELETE CASCADE,
    organisation_id BIGINT NOT NULL REFERENCES public.organisations(id) ON DELETE CASCADE,
    role TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    PRIMARY KEY (mumin_id, organisation_id)
);

CREATE INDEX IF NOT EXISTS idx_mumineen_organisations_org
    ON public.mumineen_organisations (organisation_id);

-- ---------------------------------------------------------------------
-- 5. VERIFICATION LOG
--    Keeps historical verification events while the current status/date
--    columns remain available on mumin_data for fast list views.
-- ---------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.verification_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    mumin_id BIGINT NOT NULL REFERENCES public.mumin_data(id) ON DELETE CASCADE,
    verification_type TEXT NOT NULL,
    verification_status TEXT NOT NULL,
    verified_by TEXT,
    verification_date TIMESTAMPTZ,
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT verification_log_type_check CHECK (
        verification_type IN (
            'data',
            'photo',
            'address',
            'mobile',
            'email',
            'other'
        )
    )
);

CREATE INDEX IF NOT EXISTS idx_verification_log_mumin
    ON public.verification_log (mumin_id);

CREATE INDEX IF NOT EXISTS idx_verification_log_type_status
    ON public.verification_log (verification_type, verification_status);

-- ---------------------------------------------------------------------
-- 6. FAMILY / PERSON INDEXES
-- ---------------------------------------------------------------------
CREATE INDEX IF NOT EXISTS idx_mumin_data_family_id
    ON public.mumin_data (family_id);

CREATE INDEX IF NOT EXISTS idx_mumin_data_hof_its_number
    ON public.mumin_data (hof_its_number);

CREATE INDEX IF NOT EXISTS idx_mumin_data_father_its_number
    ON public.mumin_data (father_its_number);

CREATE INDEX IF NOT EXISTS idx_mumin_data_mother_its_number
    ON public.mumin_data (mother_its_number);

CREATE INDEX IF NOT EXISTS idx_mumin_data_spouse_its_number
    ON public.mumin_data (spouse_its_number);

CREATE INDEX IF NOT EXISTS idx_mumin_data_occupation
    ON public.mumin_data (occupation);

CREATE INDEX IF NOT EXISTS idx_mumin_data_city
    ON public.mumin_data (city);

CREATE INDEX IF NOT EXISTS idx_mumin_data_gender
    ON public.mumin_data (gender);

CREATE INDEX IF NOT EXISTS idx_mumin_data_marital_status
    ON public.mumin_data (marital_status);

COMMIT;

-- =====================================================================
-- Deferred relationship cleanup / FKs
-- =====================================================================
-- The Jamaat export uses numeric 0 as a sentinel for an absent
-- Father_ITS_ID / Mother_ITS_ID / Spouse_ITS_ID. The import layer MUST
-- convert 0 to NULL before relationship FKs are introduced.
--
-- Do not run blanket UPDATE statements against legacy data here.
--
-- After the 1,584-row import has been validated, add foreign keys for
-- family/HOF/spouse and sector/sub-sector incharges only after confirming
-- that every referenced ITS number exists and that ITS numbers are unique.
-- This migration deliberately leaves those constraints deferred so that
-- existing production data cannot be broken by an import-time mismatch.
-- =====================================================================
